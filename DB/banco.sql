CREATE TABLE T_USUARIO (
    USU_ID          SERIAL       PRIMARY KEY,
    USU_LOGIN       VARCHAR(50)  NOT NULL UNIQUE,
    USU_NOME        VARCHAR(100) NOT NULL,
    USU_EMAIL       VARCHAR(255) NOT NULL UNIQUE,
    USU_SENHA       VARCHAR(255) NOT NULL,                -- hash da senha
    USU_STATUS      VARCHAR(1)   NOT NULL DEFAULT 'A',  -- A = ativo, I = inativo
    DATA_CADASTRO    TIMESTAMP    NOT NULL DEFAULT NOW(),
    DATA_NASCIMENTO  DATE         NOT NULL
);

COMMENT ON TABLE T_USUARIO IS 'Usuários cadastrados';

COMMENT ON COLUMN T_USUARIO.USU_ID        IS 'ID do usuário';
COMMENT ON COLUMN T_USUARIO.USU_LOGIN     IS 'login do usuário';
COMMENT ON COLUMN T_USUARIO.USU_NOME      IS 'Nome completo do usuário';
COMMENT ON COLUMN T_USUARIO.USU_EMAIL     IS 'E-mail de login';
COMMENT ON COLUMN T_USUARIO.USU_SENHA     IS 'Hash da senha (nunca a senha em texto)';
COMMENT ON COLUMN T_USUARIO.USU_STATUS    IS 'Situação do usuário: A = ativo, I = inativo';
COMMENT ON COLUMN T_USUARIO.DATA_CADASTRO IS 'Data e hora do cadastro';
COMMENT ON COLUMN T_USUARIO.DATA_NASCIMENTO IS 'Data de nascimento do usuário';


CREATE TABLE T_CATEGORIA (
    CAT_ID        SERIAL       PRIMARY KEY,
    USU_ID        INTEGER      NOT NULL,
    CAT_NOME      VARCHAR(100) NOT NULL,
    DATA_CADASTRO TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT FK_CATEGORIA_USUARIO FOREIGN KEY (USU_ID) REFERENCES T_USUARIO (USU_ID)
);

COMMENT ON TABLE T_CATEGORIA IS 'Categorias de gastos de cada usuário';
COMMENT ON COLUMN T_CATEGORIA.CAT_ID        IS 'ID da categoria';
COMMENT ON COLUMN T_CATEGORIA.USU_ID        IS 'Usuário dono da categoria';
COMMENT ON COLUMN T_CATEGORIA.CAT_NOME      IS 'Nome da categoria';
COMMENT ON COLUMN T_CATEGORIA.DATA_CADASTRO IS 'Data e hora de criação da categoria';


CREATE TABLE T_GRUPO (
    GRU_ID        SERIAL       PRIMARY KEY,
    USU_ID        INTEGER      NOT NULL,
    GRU_NOME      VARCHAR(100) NOT NULL,
    GRU_TIPO      VARCHAR(1)   NOT NULL DEFAULT 'P',  -- P = pessoal, C = compartilhado
    DATA_CRIACAO  TIMESTAMP    NOT NULL DEFAULT NOW(),
    CONSTRAINT FK_GRUPO_USUARIO FOREIGN KEY (USU_ID) REFERENCES T_USUARIO (USU_ID)
);

COMMENT ON TABLE T_GRUPO IS 'Grupos de gastos (pessoal ou compartilhado)';
COMMENT ON COLUMN T_GRUPO.GRU_ID       IS 'ID do grupo';
COMMENT ON COLUMN T_GRUPO.USU_ID       IS 'Usuário dono/criador do grupo';
COMMENT ON COLUMN T_GRUPO.GRU_NOME     IS 'Nome do grupo';
COMMENT ON COLUMN T_GRUPO.GRU_TIPO     IS 'Tipo do grupo: P = pessoal, C = compartilhado';
COMMENT ON COLUMN T_GRUPO.DATA_CRIACAO IS 'Data e hora de criação do grupo';


CREATE TABLE T_LIMITE (
    LIM_ID     SERIAL        PRIMARY KEY,
    CAT_ID     INTEGER       NOT NULL,
    LIM_VALOR  NUMERIC(10,2) NOT NULL,
    CONSTRAINT FK_LIMITE_CATEGORIA FOREIGN KEY (CAT_ID) REFERENCES T_CATEGORIA (CAT_ID),
    CONSTRAINT UQ_LIMITE_CATEGORIA UNIQUE (CAT_ID)  -- um limite por categoria
);

COMMENT ON TABLE T_LIMITE IS 'Limite de gasto por categoria';
COMMENT ON COLUMN T_LIMITE.LIM_ID    IS 'ID do limite';
COMMENT ON COLUMN T_LIMITE.CAT_ID    IS 'Categoria à qual o limite se aplica';
COMMENT ON COLUMN T_LIMITE.LIM_VALOR IS 'Valor do limite';


CREATE TABLE T_GASTO (
    GAS_ID         SERIAL        PRIMARY KEY,
    USU_ID         INTEGER       NOT NULL,
    GRU_ID         INTEGER       NOT NULL,
    CAT_ID         INTEGER,
    GAS_DESCRICAO  VARCHAR(255),
    GAS_VALOR      NUMERIC(10,2) NOT NULL,
    GAS_DATA       DATE          NOT NULL,
    DATA_CADASTRO  TIMESTAMP     NOT NULL DEFAULT NOW(),
    CONSTRAINT FK_GASTO_USUARIO   FOREIGN KEY (USU_ID) REFERENCES T_USUARIO (USU_ID),
    CONSTRAINT FK_GASTO_GRUPO     FOREIGN KEY (GRU_ID) REFERENCES T_GRUPO (GRU_ID),
    CONSTRAINT FK_GASTO_CATEGORIA FOREIGN KEY (CAT_ID) REFERENCES T_CATEGORIA (CAT_ID)
);

COMMENT ON TABLE T_GASTO IS 'Gastos registrados pelos usuários';
COMMENT ON COLUMN T_GASTO.GAS_ID        IS 'ID do gasto';
COMMENT ON COLUMN T_GASTO.USU_ID        IS 'Usuário que registrou o gasto';
COMMENT ON COLUMN T_GASTO.GRU_ID        IS 'Grupo ao qual o gasto pertence';
COMMENT ON COLUMN T_GASTO.CAT_ID        IS 'Categoria que classifica o gasto';
COMMENT ON COLUMN T_GASTO.GAS_DESCRICAO IS 'Descrição do gasto';
COMMENT ON COLUMN T_GASTO.GAS_VALOR     IS 'Valor do gasto';
COMMENT ON COLUMN T_GASTO.GAS_DATA      IS 'Data em que o gasto ocorreu';
COMMENT ON COLUMN T_GASTO.DATA_CADASTRO IS 'Data e hora do registro do gasto';


CREATE TABLE T_GASTO_FIXO (
    GFX_ID         SERIAL        PRIMARY KEY,
    USU_ID         INTEGER       NOT NULL,
    CAT_ID         INTEGER,
    GFX_DESCRICAO  VARCHAR(255)  NOT NULL,
    GFX_VALOR      NUMERIC(10,2) NOT NULL,
    GFX_DIA        INTEGER       NOT NULL,
    GFX_ATIVO      BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT FK_GASTOFIXO_USUARIO   FOREIGN KEY (USU_ID) REFERENCES T_USUARIO (USU_ID),
    CONSTRAINT FK_GASTOFIXO_CATEGORIA FOREIGN KEY (CAT_ID) REFERENCES T_CATEGORIA (CAT_ID)
);

COMMENT ON TABLE T_GASTO_FIXO IS 'Gastos fixos (modelos) de cada usuário';
COMMENT ON COLUMN T_GASTO_FIXO.GFX_ID        IS 'ID do gasto fixo';
COMMENT ON COLUMN T_GASTO_FIXO.USU_ID        IS 'Usuário dono do gasto fixo';
COMMENT ON COLUMN T_GASTO_FIXO.CAT_ID        IS 'Categoria do gasto fixo';
COMMENT ON COLUMN T_GASTO_FIXO.GFX_DESCRICAO IS 'Descrição do gasto fixo';
COMMENT ON COLUMN T_GASTO_FIXO.GFX_VALOR     IS 'Valor do gasto fixo';
COMMENT ON COLUMN T_GASTO_FIXO.GFX_DIA       IS 'Dia do mês do vencimento';
COMMENT ON COLUMN T_GASTO_FIXO.GFX_ATIVO     IS 'Se o gasto fixo está ativo';


