    FOREIGN KEY (GFX_ID) REFERENCES T_GASTO_FIXO (GFX_ID) ON DELETE SET NULL;

COMMENT ON COLUMN T_GASTO.GFX_ID IS 'Gasto fixo que originou este gasto, se houver';


CREATE TABLE T_PARTICIPANTE (
    PAR_ID  SERIAL  PRIMARY KEY,
    GRU_ID  INTEGER NOT NULL,
    USU_ID  INTEGER NOT NULL,
    CONSTRAINT FK_PARTICIPANTE_GRUPO   FOREIGN KEY (GRU_ID) REFERENCES T_GRUPO (GRU_ID) ON DELETE CASCADE,
    CONSTRAINT FK_PARTICIPANTE_USUARIO FOREIGN KEY (USU_ID) REFERENCES T_USUARIO (USU_ID),
    CONSTRAINT UQ_PARTICIPANTE UNIQUE (GRU_ID, USU_ID)
);

COMMENT ON TABLE T_PARTICIPANTE IS 'Participantes (membros) de cada grupo';
COMMENT ON COLUMN T_PARTICIPANTE.PAR_ID IS 'ID do participante';
COMMENT ON COLUMN T_PARTICIPANTE.GRU_ID IS 'Grupo';
COMMENT ON COLUMN T_PARTICIPANTE.USU_ID IS 'Usuário membro do grupo';